st.divider()

st.header("📊 그래프 5. 월 × 요일별 일관객 합계")

st.write(
    "날짜에서 월과 요일을 뽑아 "
    "월별·요일별 10위권 일관객 합계를 히트맵으로 나타냅니다."
)


# --------------------------------------------------
# 월과 요일 추출
# --------------------------------------------------

heatmap_df = df.dropna(
    subset=["날짜", "일관객"]
).copy()


# 월 추출
heatmap_df["월"] = heatmap_df["날짜"].dt.month


# 요일 추출
weekday_number = heatmap_df["날짜"].dt.weekday


# 요일 이름으로 변환
weekday_names = {
    0: "월요일",
    1: "화요일",
    2: "수요일",
    3: "목요일",
    4: "금요일",
    5: "토요일",
    6: "일요일"
}

heatmap_df["요일"] = weekday_number.map(
    weekday_names
)


# --------------------------------------------------
# 월 × 요일별 일관객 합계
# --------------------------------------------------

heatmap_data = (
    heatmap_df
    .groupby(
        ["월", "요일"]
    )["일관객"]
    .sum()
    .reset_index()
)


# --------------------------------------------------
# 피벗 테이블 만들기
# --------------------------------------------------

heatmap_pivot = heatmap_data.pivot(
    index="요일",
    columns="월",
    values="일관객"
)


# --------------------------------------------------
# 요일 순서 지정
# --------------------------------------------------

weekday_order = [
    "월요일",
    "화요일",
    "수요일",
    "목요일",
    "금요일",
    "토요일",
    "일요일"
]


heatmap_pivot = heatmap_pivot.reindex(
    weekday_order
)


# 월 순서 지정
heatmap_pivot = heatmap_pivot.reindex(
    columns=range(1, 13)
)


# --------------------------------------------------
# 히트맵용 데이터
# --------------------------------------------------

fig5 = px.imshow(
    heatmap_pivot,
    labels=dict(
        x="월",
        y="요일",
        color="일관객 합계"
    ),
    x=[f"{i}월" for i in range(1, 13)],
    y=weekday_order,
    title="월 × 요일별 10위권 일관객 합계",
    aspect="auto"
)


# --------------------------------------------------
# 마우스를 올렸을 때 표시
# --------------------------------------------------

fig5.update_traces(
    hovertemplate=
    "월: %{x}"
    "<br>요일: %{y}"
    "<br>일관객 합계: %{z:,}명"
    "<extra></extra>"
)


# --------------------------------------------------
# 그래프 설정
# --------------------------------------------------

fig5.update_layout(
    height=500,
    xaxis_title="월",
    yaxis_title="요일"
)


st.plotly_chart(
    fig5,
    use_container_width=True
)


